"""cadre/verify_palette.py — verify AIAgent provider/model resolution against
this host, then write the confirmed pairs to ~/.cadre/palette.yaml.

Caller-layer module (KTD4). Moved unchanged from the retired host-verify
spike during the U5 packaging pass
(docs/plans/2026-07-04-003-feat-package-as-cadre-plan.md): an installed-package
module imports ``cadre.config`` natively, so the spike's repo-relative
``sys.path`` bootstrap is gone, and ``SAFE_TOOLSETS`` is now a top-level import
instead of a lazy one (only ``_agent``'s ``run_agent`` import stays lazy — that
dependency is host-only). Invoked via the installed console command:

    cadre verify-palette

RUNS ON THE HERMES HOST with the Hermes venv Python (the interpreter cadre was
pip-installed into — the load-bearing KTD2 install target):

    ~/.hermes/hermes-agent/venv/bin/python -m cadre.cli verify-palette

---

## Two cleanly separated pieces

**(1) Live verification** — not testable on the dev machine (no hermes-agent).
    `verify_candidates(candidates)` calls AIAgent on the Hermes host and returns
    a list of VerifyRecord. Never call this here; the test suite patches `_agent`.

**(2) Pure writer** — fully testable here with fake records.
    `write_palette(records, toolsets, path)` takes a record list + declared toolsets,
    filters to ok pairs + safe toolsets, and writes owner-only 0o600 YAML.

---

## One-time host workflow

1. `cadre setup` seeds ~/.cadre/palette-candidates.yaml from the installed
   package (or edit PROVIDERS in this file) with your real strings.
2. Run `cadre verify-palette` via the Hermes venv — verifies + writes
   ~/.cadre/palette.yaml. By default this verifies a capped subset (2 per
   provider, file order) rather than every discovered candidate; pass
   `--all` to verify everything. Previously-verified pairs still in the
   candidates file are always re-verified (cap-exempt) — a re-verify never
   silently shrinks an existing palette. On success (2+ providers verified), it also
   (re)generates ~/.cadre/fleets/palette-fleet.yaml — a tool-less smoke-test
   fleet with one lane per verified provider, ready to `cadre run` with zero
   editing (see cadre/palette_fleet.py).
3. The cadre-fleet skill reads palette.yaml; compose only from its contents.

---

## Format notes

* OAuth providers (xai, openai-codex, nous): provider + bare model id.
* OpenRouter: provider="openrouter" + full "vendor/model" slug.
* NEVER put API keys here — credentials live in Hermes auth/env.
"""

