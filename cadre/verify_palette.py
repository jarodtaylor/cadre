def _load_candidates(candidates_path: Path) -> tuple[list[tuple[str, str]], list[str]]:
    """Read candidate pairs and declared toolsets from the seed YAML.

    Returns (candidates, toolsets). Falls back to the module-level PROVIDERS
    if the seed file doesn't exist or has no candidates block.
    """
    if candidates_path.exists():
        data = yaml.safe_load(candidates_path.read_text(encoding="utf-8")) or {}
        if not isinstance(data, dict):
            # A non-mapping root (top-level list/scalar) has no candidates block;
            # `or {}` only catches None, so guard the type before calling .get().
            return PROVIDERS, []
        raw_candidates = data.get("candidates") or []
        candidates = [
            (c["provider"], c["model"])
            for c in raw_candidates
            if isinstance(c, dict) and c.get("provider") and c.get("model")
        ]
        raw_toolsets = data.get("toolsets") or []
        # Guard scalar toolsets: a bare string (e.g. `toolsets: web`) must NOT be
        # iterated char-by-char. Only accept a list; a scalar string is treated as
        # invalid and discarded.
        toolsets = [t for t in raw_toolsets if isinstance(t, str)] if isinstance(raw_toolsets, list) else []
        return candidates, toolsets
    # Fallback: module-level PROVIDERS (edit before running).
    return PROVIDERS, []


def _cap_candidates(
    candidates: list[tuple[str, str]],
    per_provider: int = _DEFAULT_PER_PROVIDER_CAP,
    always_keep: frozenset[tuple[str, str]] = frozenset(),
) -> list[tuple[str, str]]:
    """Order-preserving cap: keep the first ``per_provider`` candidates for each
    provider, in file order. Pure — no I/O, no printing, no live calls; sits
    between ``_load_candidates`` and ``verify_candidates`` (R5, KTD4). A
    provider with fewer than ``per_provider`` candidates is unaffected.

    ``always_keep`` pairs are kept regardless of the cap (they do not count
    toward it): the caller passes the EXISTING palette's pairs so a capped
    re-verify RE-VERIFIES previously-verified pairs instead of silently
    pruning them from the rewritten palette (the cross-model No-ship catch —
    a routine re-verify must never strand a fleet whose pair is still valid).
    The cap bounds only the discovery flood; a pair leaves the palette solely
    by failing verification or by leaving the candidates file — both honest.

    Args:
        candidates: (provider, model) pairs, in file order.
        per_provider: Max candidates to keep per provider.
        always_keep: Pairs kept even beyond the cap (not counted toward it).

    Returns:
        The capped list, preserving the input order.
    """
    seen: dict[str, int] = {}
    capped: list[tuple[str, str]] = []
    for pair in candidates:
        if pair in always_keep:
            capped.append(pair)
            continue
        provider = pair[0]
        count = seen.get(provider, 0)
        if count < per_provider:
            capped.append(pair)
            seen[provider] = count + 1
    return capped


def _verifying_banner(to_verify: list[tuple[str, str]], total: int) -> str:
    """Build the pre-spend disclosure banner printed before the first paid call.

    States the X-of-Y split honestly (KTD4): when nothing was trimmed
    (``len(to_verify) == total`` — either ``--all`` was passed, or every
    provider was already at or under the cap), it says "all N" and never
    mentions the cap or ``--all`` — implying a trim happened when it didn't
    would be misleading. When capped, it also names exactly which pairs will
    be verified, so the operator sees the spend commitment up front rather
    than discovering it call-by-call.

    Discovered candidate strings are untrusted display input (KTD9) — each
    provider/model piece is routed through the sanitize chokepoint before
    joining, the same per-field pattern ``cli.py``'s ``validate_command`` uses
    (sanitize each piece, not the assembled line — a hostile value can't then
    forge the ``, `` separator into a fake extra pair).
    """
    footer = (
        "Unsupported or unauthenticated ones are skipped (a skip is normal, not\n"
        "an error). Provider output is hidden; set CADRE_VERIFY_VERBOSE=1 to show it."
    )
    if len(to_verify) == total:
        return f"Verifying all {total} discovered candidate(s) against this host —\n{footer}\n"

    shown = ", ".join(f"{_sanitize(p)} / {_sanitize(m)}" for p, m in to_verify)
    return (
        f"Verifying {len(to_verify)} of {total} discovered candidate(s) against this host\n"
        f"({_DEFAULT_PER_PROVIDER_CAP} per provider by default; pass --all to verify all "
        f"{total}):\n"
        f"  {shown}\n\n"
        f"{footer}\n"
    )


def _existing_palette_pairs(palette_path: Path) -> set[tuple[str, str]]:
    """The (provider, model) pairs on the EXISTING palette, or empty.

    ``write_palette`` rewrites ``palette.yaml`` from a pass's records only —
    it never merges the prior palette (verified-truth-per-cycle). ``main``
    therefore feeds these pairs back in two ways: as ``_cap_candidates``'s
    ``always_keep`` set (a capped re-verify RE-VERIFIES them rather than
    silently pruning them — the cross-model No-ship catch), and to warn about
    the remainder (pairs no longer in the candidates file at all, which WILL
    drop). Tolerant read — an absent/unreadable/malformed existing palette
    returns empty (the malformed case is preflight's business, not this
    disclosure's).
    """
    try:
        data = yaml.safe_load(palette_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, yaml.YAMLError):
        return set()
    if not isinstance(data, dict) or not isinstance(data.get("models"), list):
        return set()
    existing: set[tuple[str, str]] = set()
    for entry in data["models"]:
        if isinstance(entry, dict):
            provider, model = entry.get("provider"), entry.get("model")
            if isinstance(provider, str) and isinstance(model, str):
                existing.add((provider, model))
    return existing


def _entry_policy_banned(entry: object, policy: Policy) -> bool:
    """True iff a palette ``models`` entry is a well-formed pair the policy bans.

    Checks the entry against ``policy.check`` — the SAME authoritative,
    case-insensitive gate preflight enforces — rather than a candidate-derived
    pair set, so the prune catches a policy-banned palette entry whatever its
    casing and even if it is no longer in the candidates file. A non-dict or
    non-string-pair entry is never "banned" (it is preserved verbatim; it was
    never a runnable pair to begin with).
    """
    if not isinstance(entry, dict):
        return False
    provider, model = entry.get("provider"), entry.get("model")
    if not isinstance(provider, str) or not isinstance(model, str):
        return False
    return policy.check(provider, model) is not None


def _prune_banned_from_palette(palette_path: Path, policy: Policy) -> None:
    """Rewrite an existing palette.yaml with its policy-banned entries removed.

    Called only from ``main``'s all-excluded branch (#85): every candidate is
    policy-banned, so nothing is re-verified this cycle. Without this, a TOTAL
    ban would leave an existing palette — and its generated fleet — still
    advertising a now-banned pair, breaking the prune promise exactly when the
    ban is total. (The partial-ban path already prunes, because ``write_palette``
    rewrites from the surviving verified records; only the total-ban path,
    which returns before ``write_palette``, missed it.)

    Reads the existing palette and drops every entry the POLICY bans — checked
    directly against ``policy.check`` (``_entry_policy_banned``), the same
    case-insensitive gate preflight uses, NOT a candidate-derived pair set — so
    a banned palette entry is pruned regardless of its casing and even if it is
    no longer among the candidates. Rewrites via the canonical owner-only atomic
    writer (``approval._write_owner_only`` — temp + ``os.replace``, no
    truncation on a mid-write failure). The SURVIVING entries and the file's own
    ``toolsets`` are preserved VERBATIM — no re-verification, no invented
    verification claims — and ``generated_at`` is carried over unchanged when
    present. A fully-pruned palette is written with an empty ``models`` list
    (preflight then refuses every fleet as off-palette, the correct posture when
    every pair is banned), since ``write_palette`` cannot express a zero-pair
    palette.

    Then applies the SAME palette-fleet rule the verify path uses, to the
    pruned set: ``write_palette_fleet`` on records reconstructed from the
    survivors. 2+ surviving providers regenerates the smoke-test fleet without
    the banned pair; fewer leaves any prior fleet in place with a loud stderr
    notice (a run against it is correctly refused at preflight) — mirroring the
    verify path exactly rather than inventing a removal rule.

    No-op (leaves the file byte-untouched) when there is no readable existing
    palette, or when NONE of its entries is banned — a total ban that does not
    actually touch the palette must not perturb it. Never raises: a write
    failure warns to stderr, matching the already-exit-1 all-banned posture.
    """
    try:
        data = yaml.safe_load(palette_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, yaml.YAMLError):
        return
    if not isinstance(data, dict) or not isinstance(data.get("models"), list):
        return

    models = data["models"]
    survivors = [entry for entry in models if not _entry_policy_banned(entry, policy)]
    if len(survivors) == len(models):
        return  # no in-palette pair is banned — nothing to prune, leave as-is

    toolsets = data.get("toolsets")
    if not isinstance(toolsets, list):
        toolsets = []
    generated_at = data.get("generated_at")
    if not isinstance(generated_at, str) or not generated_at:
        generated_at = datetime.now().isoformat()
    palette = {"generated_at": generated_at, "models": survivors, "toolsets": toolsets}
    content = _PALETTE_HEADER + yaml.safe_dump(palette, sort_keys=False, allow_unicode=True)
    try:
        _write_owner_only(palette_path, content)
    except OSError as exc:
        # A write failure (symlinked target, unsafe parent) must not crash the
        # already-failing (exit 1) all-banned path — warn and move on, the same
        # never-crash posture the verify path's write_palette_fleet hook holds.
        print(
            f"[cadre] warning: could not prune banned pair(s) from {palette_path}: {exc}",
            file=sys.stderr,
        )
        return

    # Mirror the verify path's fleet hook on the pruned set: the survivors were
    # verified in a prior cycle and remain on the palette, so reconstruct ok
    # records and re-run the same generator (in the palette's own order).
    survivor_records = [
        VerifyRecord(provider=entry["provider"], model=entry["model"], ok=True)
        for entry in survivors
        if isinstance(entry, dict) and entry.get("provider") and entry.get("model")
    ]
    fleet_path = palette_path.parent / "fleets" / "palette-fleet.yaml"
    write_palette_fleet(survivor_records, path=fleet_path)


def main(all_candidates: bool = False) -> int:
    """Verify candidates against this host and write the palette (R5, R6).

    By default, verifies a capped subset (``_DEFAULT_PER_PROVIDER_CAP`` per
    provider, in file order — ``_cap_candidates``) rather than every
    discovered candidate: zero-touch discovery (#61) can surface ~70 pairs
    across a handful of providers, and paying for 70 calls before the palette
    is even usable is needless spend. Pass ``all_candidates=True`` (the CLI's
    ``--all`` flag) to verify every discovered candidate instead. Either way,
    the X-of-Y split (``_verifying_banner``) prints BEFORE the first paid call
    (``verify_candidates``, below) — the spend commitment is disclosed up
    front, never discovered call-by-call or after the fact.

    The #78 policy gate runs before any of that: a malformed policy file
    refuses outright (fail closed, no candidates even loaded for display —
    KTD2), and every policy-banned candidate is filtered out of the working
    candidate list BEFORE the cap/always-keep logic ever sees it — so a
    banned pair is refused admission before any (paid) call AND, if it was
    already on the existing palette, PRUNED from the rewritten one: it can
    never land in ``always_keep`` (that set only matters for pairs that
    remain in the candidate list) and so cannot survive the cap it would
    otherwise be exempt from. This deliberately overrides the always-keep /
    cap-exempt invariant for exactly this case (KTD4) — a tightened policy
    must be able to evict a pair the operator previously trusted.

    Args:
        all_candidates: Verify every discovered candidate, bypassing the
            per-provider cap. Defaults to False (the capped subset).

    Returns:
        0 on a successful write (at least one candidate verified ok); 1 if
        the policy file is malformed, there are no candidates to verify (or
        none survive policy filtering), or the palette write itself failed
        (a clean message is printed either way — never a raw traceback).
    """
    candidates_path = _DEFAULT_CANDIDATES_PATH.expanduser()
    palette_path = _DEFAULT_PALETTE_PATH.expanduser()

    try:
        policy_path = resolve_policy_path()
        # Pass no path so load_policy derives the override source from the env
        # (CADRE_POLICY vs the default) — an absent DEFAULT stays permissive,
        # while an absent CADRE_POLICY-named file fails closed (#85).
        policy = load_policy()
    except PolicyError as exc:
        print(_sanitize(str(exc)))
        return 1

    candidates, declared_toolsets = _load_candidates(candidates_path)

    if not candidates:
        print(
            "No candidates found. Either:\n"
            f"  • Populate {candidates_path} with a 'candidates' list — run "
            "`cadre setup` to seed it from the installed package, or\n"
            "  • Edit PROVIDERS in this file (a dev/source-checkout shortcut; "
            "not durable across a package reinstall/upgrade)"
        )
        return 1

    # Read once, early: both the policy-exclusion disclosure right below (to
    # tell an EVICTION of a previously-trusted pair apart from skipping a new
    # candidate) and the cap/always-keep logic further down need the existing
    # palette's pairs.
    existing = _existing_palette_pairs(palette_path)

    # #78: banned candidates are refused BEFORE any paid call — filtered out
    # of the working list here, before the cap/always-keep logic below ever
    # runs, so verify_candidates() is never even invoked for them.
    candidates, policy_violations = filter_pairs(candidates, policy)
    for v in policy_violations:
        # A violating pair already on the existing palette is being EVICTED —
        # that must read differently from merely skipping a new candidate
        # that was never admitted in the first place.
        eviction = " — pruned from your palette" if (v.provider, v.model) in existing else ""
        print(
            f"[cadre] policy: excluded {_sanitize(v.provider)}/{_sanitize(v.model)} "
            f"({_sanitize(v.rule)}) — not sent for verification{eviction}",
            file=sys.stderr,
        )

    if not candidates:
        # FOLD 3 (#85): every candidate is policy-banned, so nothing is
        # re-verified this cycle — but an existing palette (and its generated
        # fleet) may still advertise a now-banned pair. Prune those in-palette
        # violations before returning, so the TOTAL-ban case honors the same
        # prune promise the partial-ban path already keeps. The per-pair
        # "pruned from your palette" disclosure already fired in the loop above.
        # The prune re-checks each existing entry against the policy directly
        # (authoritative, case-insensitive) rather than the candidate-derived
        # violation set, so it also evicts a banned palette entry no longer in
        # the candidates file.
        _prune_banned_from_palette(palette_path, policy)
        print(
            f"All {len(policy_violations)} candidate(s) are excluded by policy "
            f"({_sanitize(str(policy_path))}) — nothing to verify."
        )
        return 1

    total = len(candidates)
    # Cross-model No-ship catch: a re-verify must never silently prune a
    # previously-verified pair. Existing-palette pairs still in the candidates
    # file are ALWAYS re-verified (exempt from the cap); the cap bounds only
    # the discovery flood.
    to_verify = (
        candidates
        if all_candidates
        else _cap_candidates(candidates, always_keep=frozenset(existing))
    )

    # Pre-spend disclosure #2: pairs on the existing palette that are no
    # longer in the candidates file at all cannot be re-verified and WILL
    # drop when the palette is rewritten. Warn loudly BEFORE the first paid
    # call so the operator can abort and re-add them. Policy-banned pairs are
    # excluded from this set — they already got their own, correctly-attributed
    # disclosure above; without this exclusion a pruned pair would ALSO trigger
    # this generic "no longer in the candidates file" warning, which is both
    # factually wrong (it IS still in the file — policy excluded it) and a
    # confusing double warning for the same pair.
    policy_banned_pairs = {(v.provider, v.model) for v in policy_violations}
    dropping = sorted(existing - set(to_verify) - policy_banned_pairs)
    if dropping:
        shown = ", ".join(f"{_sanitize(p)}/{_sanitize(m)}" for p, m in dropping)
        print(
            f"[cadre] warning: {len(dropping)} previously-verified pair(s) are no "
            f"longer in the candidates file and will DROP from the palette: {shown}\n"
            "  The palette is rewritten from this pass only. To keep them, add "
            "them back to ~/.cadre/palette-candidates.yaml first (re-running "
            "`cadre discover` regenerates that file from the current inventory). "
            "Fleets composed from dropped pairs will be refused at preflight.",
            file=sys.stderr,
        )

    print(_verifying_banner(to_verify, total))
    records = verify_candidates(to_verify)

    n_ok = sum(1 for r in records if r.ok)
    try:
        write_palette(records, declared_toolsets, palette_path)
    except (ValueError, OSError) as exc:
        # ValueError: zero verified providers (nothing to write). OSError: a
        # write failure — including O_NOFOLLOW's ELOOP when ~/.cadre/palette.yaml
        # is a planted symlink (the correct fail-closed behavior). Degrade to a
        # clean message + nonzero exit, never a raw traceback.
        print(f"\n✗ {exc}")
        return 1

    print(f"\n✓ {n_ok} of {len(records)} verified → {palette_path}")
    # Same KTD9 rule as verify_candidates' per-candidate lines: discovered
    # strings render sanitized, per field.
    skipped = [f"{_sanitize(r.provider)}/{_sanitize(r.model)}" for r in records if not r.ok]
    if skipped:
        print(f"  skipped {len(skipped)}: {', '.join(skipped)}")

    # Bonus artifact (U5, #61): a runnable smoke-test fleet from the just-verified
    # pairs, written as a sibling "fleets/" dir of wherever palette.yaml just
    # landed — deliberately derived from palette_path rather than a second
    # independent ~/.cadre-rooted default: every existing test above reaches
    # this point only after patching _DEFAULT_PALETTE_PATH to a tmp path, and
    # deriving from it (instead of a standalone constant no test knows to
    # patch) keeps those tests hermetic for free, with no changes to them.
    # write_palette_fleet NEVER raises — a fleet-write failure (or too few
    # verified providers) warns to stderr but must not flip this successful
    # verify to a nonzero exit; palette.yaml above is the primary deliverable.
    fleet_path = palette_path.parent / "fleets" / "palette-fleet.yaml"
    write_palette_fleet(records, path=fleet_path)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
