# Default per-provider verify cap (R5): zero-touch discovery (#61) can surface
# ~70 candidates across a handful of providers; verifying every one before the
# palette is even usable is 70 paid calls. A named constant (not a bare literal
# in the function default) so the cap size can't drift out of sync between the
# actual cap and the banner message that reports it.
_DEFAULT_PER_PROVIDER_CAP = 2

# Honesty header for the written palette (KTD4): models are live-verified, but
# toolsets are only DECLARED + safe-filtered, never tool-probed (verify_candidates
# runs a no-tool chat). A model can resolve while its search tool is unprovisioned,
# so a lane reading that toolset can run silently ungrounded. The full fix is
# host-side per-toolset probing (see RUNBOOK); until then this warns the reader.
# Shared by write_palette (the verify path) and _prune_banned_from_palette (the
# all-banned prune path), so both write byte-identical headers.
_PALETTE_HEADER = (
    "# Cadre verified palette — generated by the verify step; do not hand-edit.\n"
    "# models:   provider/model pairs confirmed by a live chat call.\n"
    "# toolsets: DECLARED safe toolsets, NOT tool-probed — provision each in the\n"
    "#           Hermes profile (see RUNBOOK) or a lane using it runs silently\n"
    "#           ungrounded (answers from training knowledge, with no error).\n"
)

